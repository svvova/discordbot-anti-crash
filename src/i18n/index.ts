export function t(
  lang: SupportedLanguage,
  key: keyof typeof translations.en,
  vars: Record<string, string | number> = {}
): string {
  const value = translations[lang]?.[key] ?? translations.en[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
